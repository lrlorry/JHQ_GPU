#!/usr/bin/env python3
"""Tables for run_warp_refine.sh: reads results/warp_refine/{ab,nsys,sanitizer}
and writes <R>/summary.md and <R>/summary.json. Measures nothing itself.

  ab/<ds>_np<np>.json            demo_jhq_v61_ab: per alpha, per kernel, recall,
                                 5 round times, per-query comparison to lanes 0
  nsys/<ds>_np<np>_a<a>_cuda_gpu_kern_sum.csv   per-kernel GPU time
  sanitizer/<ds>_np<np>_<tool>.txt               compute-sanitizer output

Speedups are paired: each round's lanes-0 time over the same round's time for
the kernel, then the median and range over rounds. Kernel latency is nsys's
median duration per launch of the refinement kernel (one launch per search of
the 1000 queries, which fit one batch).

  python3 summarize_warp.py <R>
"""
import csv
import glob
import json
import os
import re
import statistics
import sys

LANES = [0, 1, 8, 16, 32]
RULE = {("vogue-768", 128): [64], ("vogue-768", 512): [64], ("arxiv-768", 128): [100],
        ("arxiv-768", 512): [200], ("openai3-1536", 128): [8], ("openai3-1536", 512): [8],
        ("openai3-3072", 128): [4], ("openai3-3072", 512): [4], ("bge-m3", 128): [32],
        ("bge-m3", 512): [64], ("stella", 128): [16], ("stella", 512): [16]}


def kernel_times(path):
    """refine lanes -> median ns per launch; plus scan and top-k medians."""
    out = {"refine": {}, "scan": None, "topk": None, "instances": {}}
    if not os.path.exists(path):
        return out
    rows = list(csv.DictReader(open(path)))
    if not rows:
        return out
    key = lambda part: next(k for k in rows[0] if part in k)
    kn, kmed, kins = key("Name"), key("Med"), key("Instances")
    for r in rows:
        name, med, ins = r[kn], float(r[kmed]), int(float(r[kins]))
        m = re.search(r"residual_refine_group_kernel<\s*(?:\(int\))?\s*\d+\s*,\s*(?:\(int\))?\s*(\d+)\s*>", name)
        if m:
            out["refine"][int(m.group(1))] = med; out["instances"][int(m.group(1))] = ins
        elif "residual_refine_fused_kernel" in name:
            out["refine"][0] = med; out["instances"][0] = ins
        elif "scan_ivf" in name:
            out["scan"] = med if out["scan"] is None else max(out["scan"], med)
        elif "batched_topk_final_kernel" in name:
            out["topk"] = med
    return out


def main():
    R = sys.argv[1]
    rows, kern, degr, summary = [], [], [], {"configs": []}
    for jf in sorted(glob.glob(os.path.join(R, "ab", "*.json"))):
        J = json.load(open(jf))
        ds = re.match(r"(.+)_np\d+$", os.path.basename(jf)[:-5]).group(1)
        np_, nq = J["nprobe"], J["nq"]
        for A in J["alphas"]:
            a = A["alpha"]
            label = "rule" if a in RULE.get((ds, np_), []) else "full-pool/oracle"
            V = {v["lanes"]: v for v in A["variants"]}
            ms0 = V[0]["ms"]
            cfg = {"dataset": ds, "nprobe": np_, "alpha": a, "label": label, "nq": nq, "variants": {}}
            for L, v in V.items():
                qps = [nq / (m / 1000.0) for m in v["ms"]]
                sp = [m0 / m for m0, m in zip(ms0, v["ms"])]
                cfg["variants"][L] = dict(
                    recall=v["recall"], qps_med=statistics.median(qps), qps_min=min(qps), qps_max=max(qps),
                    sp_med=statistics.median(sp), sp_min=min(sp), sp_max=max(sp),
                    same_order=v["same_order"], same_set=v["same_set"], bit_identical=v["bit_identical"],
                    max_rel=v["max_rel"], kth_rel_on_set_diff=v["kth_rel_on_set_diff"])
                c = cfg["variants"][L]
                if L and c["sp_med"] < 1.0:
                    degr.append("%s/np%d a=%g L=%d: median speedup x%.3f (slower than lanes 0)" % (ds, np_, a, L, c["sp_med"]))
                if L and abs(c["recall"] - V[0]["recall"]) > 1e-4 + 1e-9:
                    degr.append("%s/np%d a=%g L=%d: recall %.4f vs %.4f" % (ds, np_, a, L, c["recall"], V[0]["recall"]))
                if L == 1 and c["bit_identical"] != nq:
                    degr.append("%s/np%d a=%g L=1: %d of %d queries not bit-identical to lanes 0 -- "
                                "the word-load kernel should be" % (ds, np_, a, nq - c["bit_identical"], nq))
            warp = [L for L in (8, 16, 32) if L in cfg["variants"]]
            cfg["best_warp"] = max(warp, key=lambda L: cfg["variants"][L]["qps_med"]) if warp else None
            K = kernel_times(os.path.join(R, "nsys", "%s_np%d_a%g_cuda_gpu_kern_sum.csv" % (ds, np_, a)))
            cfg["kernel_ns"] = K
            summary["configs"].append(cfg)
    summary["configs"].sort(key=lambda c: (c["nprobe"], c["dataset"], c["alpha"]))

    L_ = lambda c, L: c["variants"].get(L, {})
    lines = ["# v61 warp-cooperative refinement -- generated tables", "",
             "Generated by summarize_warp.py from %s. QPS: median of 5 rounds (3 searches each); "
             "x: paired speedup over lanes 0, median [min, max] over rounds." % R, "",
             "## End-to-end QPS", "",
             "| dataset | np | alpha | kind | L0 QPS | L1 (32-bit loads) | L8 | L16 | L32 | best warp L | recall L0 | max |d recall| |",
             "|---|---:|---:|---|---:|---|---|---|---|---:|---:|---:|"]
    fmt = lambda c, L: "x%.3f [%.3f, %.3f]" % (L_(c, L)["sp_med"], L_(c, L)["sp_min"], L_(c, L)["sp_max"]) if L_(c, L) else "NA"
    for c in summary["configs"]:
        r0 = L_(c, 0)["recall"]
        dr = max(abs(v["recall"] - r0) for v in c["variants"].values())
        lines.append("| %s | %d | %g | %s | %.0f | %s | %s | %s | %s | %s | %.4f | %.4f |" % (
            c["dataset"], c["nprobe"], c["alpha"], c["label"], L_(c, 0)["qps_med"],
            fmt(c, 1), fmt(c, 8), fmt(c, 16), fmt(c, 32), c["best_warp"], r0, dr))
    lines += ["", "## Per-query agreement with lanes 0 (of nq queries)", "",
              "| dataset | np | alpha | L1 bit-identical | L8 same ids/order/set | L16 | L32 | max rel dist err (L>=8, same id) | k-th dist rel diff where sets differ |",
              "|---|---:|---:|---:|---|---|---|---:|---:|"]
    for c in summary["configs"]:
        g = lambda L: "%d/%d" % (L_(c, L)["same_order"], L_(c, L)["same_set"]) if L_(c, L) else "NA"
        mr = max((L_(c, L)["max_rel"] for L in (8, 16, 32) if L_(c, L)), default=float("nan"))
        kd = max((L_(c, L)["kth_rel_on_set_diff"] for L in (8, 16, 32) if L_(c, L)), default=float("nan"))
        lines.append("| %s | %d | %g | %d/%d | %s | %s | %s | %.2e | %.2e |" % (
            c["dataset"], c["nprobe"], c["alpha"], L_(c, 1).get("bit_identical", -1), c["nq"],
            g(8), g(16), g(32), mr, kd))
    lines += ["", "## Refinement kernel latency (nsys, median us per launch = one 1000-query batch)", "",
              "| dataset | np | alpha | L0 | L1 | L8 | L16 | L32 | vectorization L0->L1 | mapping L1->best | scan | top-k | refine share L0 -> best |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for c in summary["configs"]:
        K = c["kernel_ns"]; rf = K["refine"]
        us = lambda L: "%.1f" % (rf[L] / 1e3) if L in rf else "NA"
        if 0 in rf and 1 in rf:
            best = min((L for L in (8, 16, 32) if L in rf), key=lambda L: rf[L], default=None)
            vec = "x%.2f" % (rf[0] / rf[1])
            mp = "x%.2f (L%d)" % (rf[1] / rf[best], best) if best else "NA"
            if K["scan"] and K["topk"]:
                tot0 = K["scan"] + K["topk"] + rf[0]
                totb = K["scan"] + K["topk"] + rf[best]
                share = "%.0f%% -> %.0f%%" % (100 * rf[0] / tot0, 100 * rf[best] / totb)
            else:
                share = "NA"
        else:
            vec = mp = share = "NA"
        lines.append("| %s | %d | %g | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            c["dataset"], c["nprobe"], c["alpha"], us(0), us(1), us(8), us(16), us(32), vec, mp,
            "%.1f" % (K["scan"] / 1e3) if K["scan"] else "NA",
            "%.1f" % (K["topk"] / 1e3) if K["topk"] else "NA", share))
    lines += ["", "## One L for every configuration?", "",
              "End to end: the best of L8/L16/L32 by median QPS against L16. Kernel: nsys median "
              "per launch, the fastest L against L16.", "",
              "| dataset | np | alpha | best e2e | L16 e2e | L16 / best e2e | fastest kernel | L16 kernel / fastest |",
              "|---|---:|---:|---|---:|---:|---|---:|"]
    for c in summary["configs"]:
        b = c["best_warp"]; rf = c["kernel_ns"]["refine"]
        fk = min((L for L in (8, 16, 32) if L in rf), key=lambda L: rf[L], default=None)
        lines.append("| %s | %d | %g | L%d x%.3f | x%.3f | %.3f | %s | %s |" % (
            c["dataset"], c["nprobe"], c["alpha"], b, L_(c, b)["sp_med"], L_(c, 16)["sp_med"],
            L_(c, 16)["qps_med"] / L_(c, b)["qps_med"],
            "L%d %.1f us" % (fk, rf[fk] / 1e3) if fk else "NA",
            "%.3f" % (rf[16] / rf[fk]) if fk and 16 in rf else "NA"))
    lines += ["", "## Memory safety (compute-sanitizer on the refine and top-k kernels, 64 queries)", ""]
    for f in sorted(glob.glob(os.path.join(R, "sanitizer", "*.txt"))):
        # memcheck and synccheck end on "ERROR SUMMARY", racecheck on "RACECHECK SUMMARY"
        es = [l.strip() for l in open(f, errors="ignore")
              if "ERROR SUMMARY" in l or "RACECHECK SUMMARY" in l]
        lines.append("- %s: %s" % (os.path.basename(f)[:-4], es[-1] if es else "NO ERROR SUMMARY (run did not finish?)"))
    lines += ["", "## Degradations and anomalies (all of them, none filtered)", ""]
    lines += ["- " + d for d in degr] if degr else ["- none"]
    open(os.path.join(R, "summary.md"), "w").write("\n".join(lines) + "\n")
    summary["degradations"] = degr
    json.dump(summary, open(os.path.join(R, "summary.json"), "w"), indent=1, default=str)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
