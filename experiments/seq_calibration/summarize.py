#!/usr/bin/env python3
"""Tables from out/replay.json -> out/summary.md. No new computation of results."""
import json
import os

from common import GRID, HERE

OUT = os.path.join(HERE, "out")
R = json.load(open(os.path.join(OUT, "replay.json")))

MAIN = ["FIXED-BISECT S=32", "FIXED-BISECT S=64", "FIXED-BISECT S=128", "FIXED-BISECT S=256",
        "FIXED-BISECT S=256 eps=2",
        "FIXED-ENUM S=128", "FULL-POOL S=500 (bisect)",
        "SEQ pi1=0.02 stages=16,32,64,128", "SEQ pi1=0.02 stages=32,128",
        "SEQ pi1=0.02 stages=16,32,64,128,256",
        "SEQ pi1=0.05 stages=16,32,64,128", "SEQ pi1=0.05 stages=32,128",
        "SEQ pi1=0.05 stages=16,32,64,128,256",
        "SEQ pi1=0.10 stages=16,32,64,128", "SEQ pi1=0.10 stages=32,128",
        "SEQ pi1=0.10 stages=16,32,64,128,256",
        "NO-CAL alpha=100", "NO-CAL alpha=200"]
SHORT = {"FULL-POOL S=500 (bisect)": "FULL S=500"}
BASE = "FIXED-BISECT S=128"


def nm(n):
    return SHORT.get(n, n).replace("FIXED-BISECT", "FB").replace("FIXED-ENUM", "FE") \
        .replace("stages=", "").replace("16,32,64,128,256", "16..256").replace("16,32,64,128", "16..128")


def picks(p):
    tot = sum(p.values())
    return " ".join("%s:%.0f%%" % (k, 100.0 * v / tot)
                    for k, v in sorted(p.items(), key=lambda kv: -int(kv[0])))


lines = ["# Sequential calibration replay -- generated tables", "",
         "Generated by summarize.py from out/replay.json. Loss = best held-out Recall@10 on the grid",
         "minus the pick's (paper definition). cal ms = *estimated* by cost_model.py (M2, fit on",
         "S<=128 GPU timings; M1 = fit incl. the 500-query pool), not measured GPU time.", ""]

for split in ("A", "B"):
    lines += ["## Split %s (%s)" % (split, "even calibrate / odd held-out, the paper's"
                                    if split == "A" else "odd calibrate / even held-out"), ""]
    for r in [x for x in R if x["split"] == split]:
        lines += ["### %s  (ceiling %.4f, GT oracle alpha=%d)" % (r["config"], r["ceiling"], r["oracle_alpha"]),
                  "", "held-out recall by alpha: " +
                  ", ".join("%s:%.4f" % (a, r["held_recall"][str(a)]) for a in GRID), "",
                  "| policy | picks | loss mean | p95 | max | P(loss>1e-3) | n used | launches | query-searches | cal ms M2 (p95) | cal ms M1 |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for n in MAIN:
            p = r["policies"][n]
            lines.append("| %s | %s | %.4f | %.4f | %.4f | %.3f | %.0f | %.1f | %.0f | %.1f (%.1f) | %.1f |" % (
                nm(n), picks(p["picks"]), p["loss_mean"], p["loss_p95"], p["loss_max"],
                p["frac_over_1e-3"], p["n_used_mean"], p["launches_mean"], p["query_searches_mean"],
                p["est_cal_ms_mean"], p["est_cal_ms_p95"], p["est_cal_ms_M1_mean"]))
        pp = r["paired_primary_vs_base"]
        lines += ["", "Paired, SEQ pi1=0.02 16..128 vs FB S=128 (same permutation): same pick %.1f%%, "
                  "SEQ lower loss %.1f%%, higher loss %.1f%%, SEQ cheaper (M2) %.1f%%, mean cal-ms diff %+.1f ms." % (
                      100 * pp["same_pick"], 100 * pp["seq_lower_loss"], 100 * pp["seq_higher_loss"],
                      100 * pp["seq_cheaper_cal"], pp["cal_ms_diff_mean"]), ""]
        if split == "A":
            lines += ["n-used distribution: " + "; ".join(
                "%s {%s}" % (nm(n), ", ".join("%s:%d" % kv for kv in r["policies"][n]["n_used_dist"].items()))
                for n in MAIN if n.startswith("SEQ")), ""]
            lines += ["Mean launches per alpha (200 = reference):", "",
                      "| policy | " + " | ".join(map(str, GRID)) + " |",
                      "|---|" + "---:|" * len(GRID)]
            for n in MAIN:
                if n.startswith("NO-CAL"):
                    continue
                pa = r["policies"][n]["per_alpha_launches_mean"]
                pq = r["policies"][n]["per_alpha_queries_mean"]
                lines.append("| %s | " % nm(n) + " | ".join(
                    "%.2f (%.0fq)" % (pa[str(a)], pq[str(a)]) for a in GRID) + " |")
            lines += ["", "Total cost over a service life of B 500-query batches, mean ms (M2), "
                      "and ratio to FB S=128:", "",
                      "| policy | B=1 | B=10 | B=100 | B=1000 | B=10000 |", "|---|---:|---:|---:|---:|---:|"]
            base = r["policies"][BASE]["lifetime_ms_mean"]
            for n in MAIN:
                lt = r["policies"][n]["lifetime_ms_mean"]
                lines.append("| %s | " % nm(n) + " | ".join(
                    "%.0f (%.3f)" % (lt[B], lt[B] / base[B]) for B in ("1", "10", "100", "1000", "10000")) + " |")
            lines.append("")

open(os.path.join(OUT, "summary.md"), "w").write("\n".join(lines) + "\n")
print("wrote out/summary.md (%d lines)" % len(lines))
