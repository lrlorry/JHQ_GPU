#!/usr/bin/env python3
"""Tables for run_v62.sh. Reads <R>/check/*.json (per-query checks),
<R>/perf/*.json (timing), <R>/perf/stages_summary.json (stage_times.py) and
<R>/sanitizer/*.txt; writes <R>/summary.md and <R>/summary.json. Measures
nothing itself.

Speedup of G over G = 0 is paired: within a round, QPS(G) / QPS(0) -- the same
queries, the same batches, back to back -- then median and [min, max] over the
five rounds. Latency ratio likewise uses each round's median batch latency.

The GO / CONDITIONAL GO / NO-GO lines apply the task's criteria literally, as a
first reading; the report makes the call:
  GO           checks pass, and at b = 8 or 32 some workload has a stable
               end-to-end speedup >= 1.15 (median >= 1.15, every round >= 1.10)
  CONDITIONAL  best stable gain at b <= 32 between 1.05 and 1.15
  NO-GO        otherwise
"""
import glob
import json
import os
import statistics
import sys


def main():
    R = sys.argv[1]
    out, lines = {"check": [], "perf": [], "stages": [], "sanitizer": {}}, []
    lines += ["# v62 list-group primary screening -- generated tables", "",
              "Generated by summarize_v62.py from %s." % R, "",
              "## Correctness: every G against G = 0 (v61's scan), same index and queries", "",
              "| dataset | alpha | b | G | probes same | primary top-ck same | tie-only | NON-TIE | max abs primary diff | final same order | same set | bit-identical | max rel final | recall G / G0 |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    nontie = probebad = 0
    for jf in sorted(glob.glob(os.path.join(R, "check", "*.json"))):
        J = json.load(open(jf))
        ds = os.path.basename(jf)[:-5]
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            for G, v in sorted(V.items()):
                if G == 0 or "probe_same" not in v:
                    continue
                n = run["nused"]
                nontie += v["topck_nontie"]; probebad += (v["probe_same"] != n)
                lines.append("| %s | %g | %d | %d | %d/%d | %d | %d | %d | %.2e | %d | %d | %d | %.2e | %.4f / %.4f |" % (
                    ds, run["alpha"], run["batch"], G, v["probe_same"], n, v["topck_same"], v["topck_tie_only"],
                    v["topck_nontie"], v["primary_max_abs"], v["final_same_order"], v["final_same_set"],
                    v["final_bit_identical"], v["final_max_rel"], v["recall"], V[0]["recall"]))
                out["check"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"], G=G, nused=n,
                                         **{k: v[k] for k in v if k not in ("G", "lat_med_ms", "lat_p95_ms", "qps")}))
    lines += ["", "Non-tie primary top-ck differences in total: **%d**; probe mismatches: **%d**." % (nontie, probebad)]

    lines += ["", "## Memory safety (compute-sanitizer on scan_ivf_group_kernel and merge_group_topk_kernel)", ""]
    for f in sorted(glob.glob(os.path.join(R, "sanitizer", "*.txt"))):
        es = [l.strip() for l in open(f, errors="ignore") if "ERROR SUMMARY" in l or "RACECHECK SUMMARY" in l]
        lines.append("- %s: %s" % (os.path.basename(f)[:-4], es[-1] if es else "no summary line (did not finish?)"))
        out["sanitizer"][os.path.basename(f)[:-4]] = es[-1] if es else None

    lines += ["", "## End-to-end: paired speedup over G = 0, median [min, max] of 5 rounds", "",
              "| dataset | alpha | b | G0 latency ms | G0 QPS | G1 | G2 | G4 | G8 | best G | best latency ms |",
              "|---|---:|---:|---:|---:|---|---|---|---|---:|---:|"]
    best_small = []
    for jf in sorted(glob.glob(os.path.join(R, "perf", "*.json"))):
        if jf.endswith("stages_summary.json"):
            continue
        J = json.load(open(jf))
        ds = os.path.basename(jf)[:-5]
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            q0, l0 = V[0]["qps"], V[0]["lat_med_ms"]
            cells, best = {}, (0, 1.0, statistics.median(l0))
            for G in (1, 2, 4, 8):
                if G not in V:
                    continue
                sp = [a / b for a, b in zip(V[G]["qps"], q0)]
                cells[G] = (statistics.median(sp), min(sp), max(sp))
                if statistics.median(sp) > best[1]:
                    best = (G, statistics.median(sp), statistics.median(V[G]["lat_med_ms"]))
            lines.append("| %s | %g | %d | %.3f | %.0f | %s | %s | %s | %s | %s | %.3f |" % (
                ds, run["alpha"], run["batch"], statistics.median(l0), statistics.median(q0),
                *["x%.3f [%.3f, %.3f]" % cells[G] if G in cells else "NA" for G in (1, 2, 4, 8)],
                ("G%d" % best[0]) if best[0] else "G0", best[2]))
            out["perf"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"],
                                    g0_latency_ms=statistics.median(l0), g0_qps=statistics.median(q0),
                                    speedup={G: cells[G] for G in cells},
                                    scratch_mib={v["G"]: v.get("group_scratch_mib") for v in run["variants"]},
                                    used_mib={v["G"]: v.get("used_mib") for v in run["variants"]}))
            if run["batch"] <= 32:
                stable = [(G, c[0]) for G, c in cells.items() if c[1] >= 1.10]
                best_small.append(max([m for _, m in stable], default=0.0))

    st = os.path.join(R, "perf", "stages_summary.json")
    if os.path.exists(st):
        S = json.load(open(st))
        lines += ["", "## GPU time per search by stage (nsys, median us) and kernels per search", "",
                  "| dataset | alpha | b | G | scan | merge | refine | other GPU | host+gaps | latency ms | kernels |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for s in sorted(S, key=lambda s: (s["tag"], s["alpha"], s["batch"], s["G"])):
            u = s["stages_us"]
            other = sum(v for k, v in u.items() if k not in ("scan", "merge", "refine") and v == v)
            lines.append("| %s | %g | %d | %d | %.1f | %.1f | %.1f | %.1f | %.1f | %.3f | %s |" % (
                s["tag"], s["alpha"], s["batch"], s["G"], u["scan"], u["merge"], u["refine"], other,
                s["host_gaps_us"], s["latency_ms"], "%g" % s["kernels"] if s["kernels"] == s["kernels"] else "-"))
        out["stages"] = S

    lines += ["", "## Scratch and device memory (MiB) per G", "",
              "| dataset | alpha | b | group scratch G2 / G4 / G8 | device memory used G0 / G8 |",
              "|---|---:|---:|---|---|"]
    for p in out["perf"]:
        sc, um = p["scratch_mib"], p["used_mib"]
        lines.append("| %s | %g | %d | %s / %s / %s | %s / %s |" % (
            p["dataset"], p["alpha"], p["batch"], sc.get(2), sc.get(4), sc.get(8), um.get(0), um.get(8)))

    best = max(best_small, default=0.0)
    verdict = ("GO" if (nontie == 0 and probebad == 0 and best >= 1.15) else
               "CONDITIONAL GO" if (nontie == 0 and probebad == 0 and best >= 1.05) else "NO-GO")
    lines += ["", "## First reading of the GO criteria", "",
              "Best stable end-to-end speedup at b <= 32 (every round >= 1.10): x%.3f; checks: %s -> **%s**" % (
                  best, "pass" if nontie == 0 and probebad == 0 else "FAIL", verdict)]
    out["verdict"] = verdict
    open(os.path.join(R, "summary.md"), "w").write("\n".join(lines) + "\n")
    json.dump(out, open(os.path.join(R, "summary.json"), "w"), indent=1, default=str)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
