#!/usr/bin/env python3
"""Tables for exp47_bench.sh (Experiments 4 and 7). Reads <dir>/*.json from
demo_jhq_v65_batch; writes <out.md> and <out>.json. Measures nothing itself.

Variants: 0 = v61 L16, 1000 = v61 L0, 102/104/108 = v63 G2/G4/G8 (shared
bound), -1 = v65 scheduled. Speedups are paired within a round (QPS ratio),
median [min, max] over the rounds. The oracle is the best of the fixed
primary choices {0, 102, 104, 108} per (configuration, alpha, b), by median
paired speedup over 0 -- a bound read off the test queries, never a method.
Regret of the schedule = oracle / scheduled.

  python3 summarize_bench.py <dir> <out.md>
"""
import glob
import json
import math
import os
import statistics as st
import sys

TRAIN = {("vogue-768", 128, 64.0), ("arxiv-768", 128, 100.0), ("arxiv-768", 128, 200.0), ("openai3-3072", 128, 4.0)}
NAMES = {0: "v61 L16", 1000: "v61 L0", 102: "v63 G2", 104: "v63 G4", 108: "v63 G8", -1: "v65 sched"}


def paired(a, b):
    r = [x / y for x, y in zip(a, b)]
    return st.median(r), min(r), max(r)


def gmean(xs):
    xs = [x for x in xs if x and x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else float("nan")


def main():
    d, out = sys.argv[1], sys.argv[2]
    rows = []
    corr = []
    for jf in sorted(glob.glob(os.path.join(d, "*.json"))):
        J = json.load(open(jf))
        if "runs" not in J:
            continue
        ds = os.path.basename(jf)[:-5].rsplit("_np", 1)[0]
        npb = J["nprobe"]
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            if 0 not in V:
                continue
            key = (ds, npb, float(run["alpha"]))
            r = dict(dataset=ds, nprobe=npb, alpha=run["alpha"], batch=run["batch"], sched_G=run.get("sched_G"),
                     cv=J.get("sched_cv"), held_out=key not in TRAIN, nused=run["nused"],
                     lat_ms={g: st.median(V[g]["lat_med_ms"]) for g in V},
                     qps={g: st.median(V[g]["qps"]) for g in V},
                     recall={g: V[g]["recall"] for g in V},
                     over_l16={g: paired(V[g]["qps"], V[0]["qps"]) for g in V},
                     over_l0={g: paired(V[g]["qps"], V[1000]["qps"]) for g in V} if 1000 in V else {})
            fixed = {g: r["over_l16"][g][0] for g in (0, 102, 104, 108) if g in V}
            og = max(fixed, key=fixed.get)
            r["oracle_G"], r["oracle"] = og, fixed[og]
            r["regret"] = fixed[og] / r["over_l16"][-1][0] if -1 in V else float("nan")
            rows.append(r)
            for g, v in V.items():
                if g != 0 and "topck_nontie" in v:
                    corr.append(dict(dataset=ds, nprobe=npb, alpha=run["alpha"], batch=run["batch"], G=g,
                                     nontie=v["topck_nontie"], tie_only=v["topck_tie_only"], probes=v["probe_same"],
                                     same_set=v["final_same_set"], same_order=v["final_same_order"], nused=run["nused"],
                                     recall=v["recall"], recall0=V[0]["recall"]))
    L = ["# Experiments 4 and 7: scheduled pipeline (v65) against every fixed choice", "",
         "Generated by summarize_bench.py. Paired speedup over v61 L16 (variant 0), median of 5 rounds. "
         "Oracle = best fixed primary choice per row, read off the test queries (a bound, not a method). "
         "Training rows (*) fitted the schedule's rule; the rest are held out.", "",
         "## Correctness", "",
         "Non-tie primary top-ck differences against v61 L16, all variants and rows: **%d**; "
         "queries with a different final id set: %d of %d compared." % (
             sum(c["nontie"] for c in corr), sum(c["nused"] - c["same_set"] for c in corr), sum(c["nused"] for c in corr)),
         "", "## End to end", "",
         "| dataset | np | alpha | b | v61 L16 ms | v61 L0 | v63 G2 | v63 G4 | v63 G8 | v65 sched (G) | oracle (G) | regret | recall L16 / sched |",
         "|---|---:|---:|---:|---:|---|---|---|---|---|---|---:|---|"]
    for r in sorted(rows, key=lambda r: (r["held_out"], r["dataset"], r["nprobe"], r["alpha"], r["batch"])):
        f = lambda g: "x%.2f" % r["over_l16"][g][0] if g in r["over_l16"] else "-"
        L.append("| %s%s | %d | %g | %d | %.3f | %s | %s | %s | %s | x%.2f [%.2f, %.2f] (%s) | x%.2f (%s) | %.3f | %.4f / %.4f |" % (
            r["dataset"], "" if r["held_out"] else "*", r["nprobe"], r["alpha"], r["batch"], r["lat_ms"][0],
            f(1000), f(102), f(104), f(108), *r["over_l16"][-1], r["sched_G"], r["oracle"],
            {0: "G0", 102: "G2", 104: "G4", 108: "G8"}[r["oracle_G"]], r["regret"], r["recall"][0], r["recall"][-1]))
    L += ["", "## Summary by batch size (geometric means over rows)", "",
          "| set | b | rows | v61 L0 | v63 G2 | v63 G4 | v63 G8 | v65 sched | oracle | sched worst regret | sched min speedup |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    summ = []
    for name, sel in (("training", lambda r: not r["held_out"]), ("held-out", lambda r: r["held_out"]), ("all", lambda r: True)):
        for b in (8, 32, 256, 1000):
            R = [r for r in rows if sel(r) and r["batch"] == b]
            if not R:
                continue
            g = {k: gmean([r["over_l16"][k][0] for r in R if k in r["over_l16"]]) for k in (1000, 102, 104, 108, -1)}
            orc = gmean([r["oracle"] for r in R])
            worst = max(r["regret"] for r in R)
            mins = min(r["over_l16"][-1][0] for r in R)
            L.append("| %s | %d | %d | x%.3f | x%.3f | x%.3f | x%.3f | x%.3f | x%.3f | %.3f | x%.3f |" % (
                name, b, len(R), g[1000], g[102], g[104], g[108], g[-1], orc, worst, mins))
            summ.append(dict(set=name, batch=b, rows=len(R), gmean={NAMES[k]: v for k, v in g.items()}, oracle=orc,
                             worst_regret=worst, sched_min=mins))
    open(out, "w").write("\n".join(L) + "\n")
    json.dump(dict(rows=rows, correctness=corr, summary=summ), open(out[:-3] + ".json", "w"), indent=1, default=str)
    print("\n".join(L))


if __name__ == "__main__":
    main()
