#!/usr/bin/env python3
"""Experiment 2 (v63) pilot, offline half: how often would a local quota b_i < ck
certify the global primary top-ck, for v62's grouping?

Reads <prefix>_a<alpha>.dump files written by demo_jhq_v62_batch with
JHQ_BP_DUMP=1 (the exact G = 1 top-ck of every query, its probe ids, the IVF
list sizes) and places every global top-ck candidate in the group v62 gives it
for G = 2, 4, 8: the probed lists laid end to end in probe order, cut at
floor(total * g / G). n_i = how many of the query's global top-ck fall in
group i.

Why n_i decides everything. Let group i return its top-b_i under the key order
and u_i = its (b_i + 1)-th key; tau = the ck-th key of the union of what was
returned. The returned union is certified to hold the global top-ck iff no
u_i precedes tau -- and that holds iff n_i <= b_i for every i:
  if every n_i <= b_i, each group returned all of its global top-ck members, so
    tau is the true ck-th key and each u_i, not a member, comes after it;
  if some n_i > b_i, group i's (b_i + 1)-th key is a member, so it precedes or
    is the true ck-th key, which is at or before tau (tau is the ck-th of a
    subset), and the certificate fails.
So a policy's certification rate is the share of queries with n_i <= b_i for
all i, and needs no GPU run of the policy itself.

Policies (b_i rounded up; never above ck, where the policy is v62's):
  equal        b_i = s * ck / G for slack s. Under v62's split the groups hold
               equal candidate counts (to one), so quotas proportional to
               candidate counts are these same quotas.
  calibrated   b_i = s * ck * w_i, w_i = a per-group share fitted on the first
               half of the queries (the 99th percentile of n_i / ck there),
               scored on the second half only.
Also reported: the skew of the split, max_i n_i / (ck / G) -- the slack equal
quotas need for that query -- and the total returned, sum_i b_i, against
v62's G * ck.

  python3 exp2_quota_study.py <out.md> <dump>...
"""
import json
import math
import os
import sys

import numpy as np


def load(path):
    a = np.fromfile(path, dtype=np.int32)
    nused, nprobe, ck, nlist = (int(x) for x in a[:4])
    o = 4
    sizes = a[o:o + nlist].astype(np.int64); o += nlist
    probes = a[o:o + nused * nprobe].reshape(nused, nprobe); o += nused * nprobe
    pos = a[o:o + nused * ck].reshape(nused, ck); o += nused * ck
    val = a[o:o + nused * ck].view(np.float32).reshape(nused, ck); o += nused * ck
    assert o == a.size, "dump size mismatch"
    return nused, nprobe, ck, nlist, sizes, probes, pos, val


def group_counts(dump, Gs):
    """n[G] = array [nused][G] of global top-ck members per group."""
    nused, nprobe, ck, nlist, sizes, probes, pos, val = dump
    offsets = np.concatenate([[0], np.cumsum(sizes)])
    out = {G: np.zeros((nused, G), dtype=np.int64) for G in Gs}
    bad = 0
    for q in range(nused):
        pr = probes[q]
        ps = sizes[pr]
        poff = np.concatenate([[0], np.cumsum(ps)])
        total = int(poff[-1])
        rank = {int(l): j for j, l in enumerate(pr)}
        p = pos[q][pos[q] >= 0].astype(np.int64)
        lists = np.searchsorted(offsets, p, side="right") - 1
        js = np.array([rank.get(int(l), -1) for l in lists])
        if (js < 0).any():
            bad += int((js < 0).sum())
            js = np.where(js < 0, 0, js)
        lt = poff[js] + (p - offsets[lists])
        for G in Gs:
            starts = (total * np.arange(G + 1)) // G       # cuts, as the kernel takes them
            g = np.searchsorted(starts, lt, side="right") - 1
            out[G][q] = np.bincount(np.clip(g, 0, G - 1), minlength=G)
    return out, bad


def main():
    md, dumps = sys.argv[1], sys.argv[2:]
    Gs = (2, 4, 8)
    slack = (1.0, 1.25, 1.5, 2.0, 3.0, 4.0)
    cal_slack = (1.0, 1.1, 1.25, 1.5)
    L = ["# Experiment 2 pilot: would smaller local quotas certify the global top-ck?", "",
         "Generated by exp2_quota_study.py. n_i = global top-ck members in group i "
         "(v62's split: probed lists end to end in probe order -- nearest list first -- "
         "cut into G equal shares). A quota certifies iff n_i <= b_i for every group.", ""]
    J = []
    for path in dumps:
        tag = os.path.basename(path)[:-5]
        dump = load(path)
        nused, nprobe, ck = dump[0], dump[1], dump[2]
        counts, bad = group_counts(dump, Gs)
        L += ["## %s (ck = %d, %d queries%s)" % (tag, ck, nused,
              "" if bad == 0 else "; %d candidates outside the probed lists -- layout assumption broken" % bad), ""]
        L += ["Share of the global top-ck held by each group (mean over queries; group 0 = nearest lists):", ""]
        for G in Gs:
            share = counts[G].mean(axis=0) / ck
            L.append("- G=%d: %s" % (G, " ".join("%.3f" % s for s in share)))
        L += ["", "| G | skew med | skew p90 | skew p99 | skew max | " +
              " | ".join("equal s=%g" % s for s in slack) + " | " +
              " | ".join("calibrated s=%g (held-out)" % s for s in cal_slack) +
              " | returned / G*ck at best certifying-99% policy |",
              "|---:|" + "---:|" * (4 + len(slack) + len(cal_slack) + 1)]
        for G in Gs:
            n = counts[G]
            skew = n.max(axis=1) / (ck / G)
            row = [np.median(skew), np.quantile(skew, 0.9), np.quantile(skew, 0.99), skew.max()]
            eq = []
            best = None
            for s in slack:
                b = min(ck, math.ceil(s * ck / G))
                ok = (n.max(axis=1) <= b).mean()
                eq.append(ok)
                if ok >= 0.99 and best is None:
                    best = ("equal s=%g" % s, G * b / (G * ck))
            half = nused // 2
            w = np.quantile(n[:half] / ck, 0.99, axis=0)
            cal = []
            for s in cal_slack:
                b = np.minimum(ck, np.ceil(s * ck * w)).astype(np.int64)
                ok = (n[half:] <= b[None, :]).all(axis=1).mean()
                cal.append(ok)
                if ok >= 0.99 and (best is None or b.sum() / (G * ck) < best[1]):
                    best = ("calibrated s=%g" % s, b.sum() / (G * ck))
            L.append("| %d | %.2f | %.2f | %.2f | %.2f | " % (G, *row) +
                     " | ".join("%.1f%%" % (100 * x) for x in eq) + " | " +
                     " | ".join("%.1f%%" % (100 * x) for x in cal) + " | " +
                     ("%s: %.2f" % best if best else "none certifies 99%") + " |")
            J.append(dict(tag=tag, ck=ck, nused=nused, G=G, outside=bad,
                          share=(n.mean(axis=0) / ck).tolist(),
                          skew=dict(median=row[0], p90=row[1], p99=row[2], max=row[3]),
                          equal={str(s): eq[i] for i, s in enumerate(slack)},
                          calibrated={str(s): cal[i] for i, s in enumerate(cal_slack)},
                          calibrated_w=w.tolist(),
                          best_99=best))
        L.append("")
    open(md, "w").write("\n".join(L) + "\n")
    json.dump(J, open(md[:-3] + ".json", "w"), indent=1, default=float)
    print("\n".join(L))


if __name__ == "__main__":
    main()
