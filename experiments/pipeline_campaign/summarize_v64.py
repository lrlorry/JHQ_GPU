#!/usr/bin/env python3
"""Tables for exp3_v64.sh. Reads <R>/check/*.json (per-query checks of route
modes 1 and 2 against 0), <R>/perf/*.json (timing) and <R>/perf/*_trace*.csv
(nsys); writes <R>/summary.md and <R>/summary.json. Measures nothing itself.

From the trace, per search (split as stage_times.py does: a search ends with
its final top-k kernel), the front end -- every kernel before the scan, i.e.
rotation, centroid GEMM, probe selection, table:
  front span  first kernel's start to the scan's start (what the scan waits)
  front sum   the sum of those kernels' durations
  overlap     front sum - front span; > 0 only when kernels ran concurrently
Mode 2 can only help through the span; mode 1 against 0 shows the cost of the
change of coordinates alone.

  python3 summarize_v64.py <R>
"""
import csv
import glob
import gzip
import json
import os
import re
import statistics as st
import sys
from collections import defaultdict


def read_trace(path):
    op = gzip.open if path.endswith(".gz") else open
    with op(path, "rt") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return []
    cols = rows[0].keys()
    ks = next(c for c in cols if c.startswith("Start"))
    kd = next(c for c in cols if c.startswith("Duration"))
    kn = next(c for c in cols if c == "Name" or c.endswith("Name") and "NVTX" not in c)
    out = []
    for r in rows:
        m = re.match(r"^(a[\d.]+\|b\d+\|G-?\d+\|r\d+)/(.*)$", r[kn])
        if not m:
            continue
        name = m.group(2)
        if "memcpy" in name.lower() or "memset" in name.lower():
            continue
        out.append((float(r[ks]), float(r[kd]), name, m.group(1)))
    out.sort()
    return out


def fronts(trace):
    by = defaultdict(list)
    for t, dur, name, rng in trace:
        m = re.search(r"a([\d.]+)\|b(\d+)\|G(-?\d+)\|r(\d+)", rng)
        by[(float(m.group(1)), int(m.group(2)), int(m.group(3)))].append((t, dur, name))
    res = {}
    for key, rows in by.items():
        S, cur = [], []
        for t, dur, name in rows:
            cur.append((t, dur, name))
            if "batched_topk_final" in name:
                S.append(cur); cur = []
        out = []
        for s in S:
            i_scan = next((i for i, x in enumerate(s) if "scan_ivf" in x[2]), None)
            if i_scan is None:
                continue
            t0 = min(x[0] for x in s)
            front = s[:i_scan]
            span = s[i_scan][0] - t0
            fsum = sum(x[1] for x in front)
            out.append(dict(front_span=span / 1e3, front_sum=fsum / 1e3, overlap=(fsum - span) / 1e3,
                            total_span=(max(x[0] + x[1] for x in s) - t0) / 1e3, kernels=len(s)))
        res[key] = out
    return res


def main():
    R = sys.argv[1]
    L = ["# v64 routing by Pi^T c -- generated tables", "", "Generated by summarize_v64.py from %s." % R, "",
         "## Correctness: modes 1 and 2 against mode 0 (v61's routing), same index and queries", "",
         "| dataset | alpha | b | mode | probes same | primary top-ck same | tie-only | NON-TIE | NON-TIE with same probes | "
         "max abs routing-distance diff | max dot diff / max dot | final same order | same set | recall mode / 0 |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    out = {"check": [], "perf": [], "front": [], "rotation": {}}
    bad = 0
    for jf in sorted(glob.glob(os.path.join(R, "check", "*.json"))):
        J = json.load(open(jf)); ds = os.path.basename(jf)[:-5]
        out["rotation"][ds] = dict(orth_max_abs=J.get("orth_max_abs"), norm_max_rel=J.get("norm_max_rel"))
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            for m in (1, 2):
                if m not in V or "probe_same" not in V[m]:
                    continue
                v = V[m]; n = run["nused"]; bad += v["nontie_same_probes"]
                L.append("| %s | %g | %d | %d | %d/%d | %d | %d | %d | %d | %.2e | %.2e | %d | %d | %.4f / %.4f |" % (
                    ds, run["alpha"], run["batch"], m, v["probe_same"], n, v["topck_same"], v["topck_tie_only"],
                    v["topck_nontie"], v["nontie_same_probes"], v["route_dist_max_abs"], v["route_dot_max_rel"],
                    v["final_same_order"], v["final_same_set"], v["recall"], V[0]["recall"]))
                out["check"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"], mode=m, nused=n,
                                         **{k: v[k] for k in v if k not in ("G", "lat_med_ms", "lat_p95_ms", "qps")}))
    L += ["", "NON-TIE primary differences on queries whose probes agree: **%d** (must be 0)." % bad, "",
          "Rotation: " + "; ".join("%s max|Pi^T Pi - I| = %.2e, max rel ||Pi^T c||^2 vs ||c||^2 = %.2e" % (
              ds, r["orth_max_abs"] or float("nan"), r["norm_max_rel"] or float("nan"))
              for ds, r in sorted(out["rotation"].items())), ""]

    L += ["## End-to-end: paired speedup over mode 0, median [min, max] of 5 rounds", "",
          "| dataset | alpha | b | mode 0 latency ms | mode 1 | mode 2 | mode 2 over 1 |", "|---|---:|---:|---:|---|---|---|"]
    T = {}
    for jf in sorted(glob.glob(os.path.join(R, "perf", "*.json"))):
        J = json.load(open(jf)); ds = os.path.basename(jf)[:-5]
        tr = sorted(glob.glob(os.path.join(R, "perf", ds + "_trace*cuda_gpu_trace*")))
        if tr:
            T[ds] = fronts(read_trace(tr[0]))
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            sp = {}
            for m, base in ((1, 0), (2, 0), (2, 1)):
                r = [a / b for a, b in zip(V[m]["qps"], V[base]["qps"])]
                sp[(m, base)] = (st.median(r), min(r), max(r))
            L.append("| %s | %g | %d | %.3f | x%.3f [%.3f, %.3f] | x%.3f [%.3f, %.3f] | x%.3f [%.3f, %.3f] |" % (
                ds, run["alpha"], run["batch"], st.median(V[0]["lat_med_ms"]), *sp[(1, 0)], *sp[(2, 0)], *sp[(2, 1)]))
            out["perf"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"],
                                    lat0=st.median(V[0]["lat_med_ms"]),
                                    speedup={"%d/%d" % k: v for k, v in sp.items()}))
    L += ["", "## Front end per search (nsys, median us): first kernel to the scan's start, against the sum of those kernels", "",
          "| dataset | alpha | b | span 0 | span 1 | span 2 | sum 0 | sum 2 | overlap 2 | front saved by 2 vs 0 | kernels 0 / 2 |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for ds, F in sorted(T.items()):
        for (a, b) in sorted({(k[0], k[1]) for k in F}):
            med = {}
            for m in (0, 1, 2):
                xs = F.get((a, b, m), [])
                med[m] = {f: st.median([x[f] for x in xs]) if xs else float("nan")
                          for f in ("front_span", "front_sum", "overlap", "kernels")}
            L.append("| %s | %g | %d | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %g / %g |" % (
                ds, a, b, med[0]["front_span"], med[1]["front_span"], med[2]["front_span"], med[0]["front_sum"],
                med[2]["front_sum"], med[2]["overlap"], med[0]["front_span"] - med[2]["front_span"],
                med[0]["kernels"], med[2]["kernels"]))
            out["front"].append(dict(dataset=ds, alpha=a, batch=b, **{"mode%d" % m: med[m] for m in med}))
    open(os.path.join(R, "summary.md"), "w").write("\n".join(L) + "\n")
    json.dump(out, open(os.path.join(R, "summary.json"), "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
