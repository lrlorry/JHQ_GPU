#!/usr/bin/env python3
"""Tables for exp2_v63.sh: the shared bound (v63, variant 100 + G) against
v62's independent groups (variant G) and v61's scan (variant 0), one index.

Reads <R>/check/*.json, <R>/perf/*.json and <R>/perf/stages_summary.json
(stage_times.py); writes <R>/summary.md and <R>/summary.json. Speedups are
paired within a round (QPS ratio), median [min, max] over the rounds.

  python3 summarize_v63.py <R>
"""
import glob
import json
import os
import statistics as st
import sys


def paired(a, b):
    r = [x / y for x, y in zip(a, b)]
    return st.median(r), min(r), max(r)


def main():
    R = sys.argv[1]
    L = ["# v63 shared bound -- generated tables", "", "Generated by summarize_v63.py from %s." % R, "",
         "## Correctness", "",
         "| dataset | alpha | b | G | NON-TIE vs G0 (v62 / v63) | top-ck identical v63 vs v62 | final identical v63 vs v62 | recall v62 / v63 |",
         "|---|---:|---:|---:|---|---|---|---|"]
    out = {"check": [], "perf": []}
    for jf in sorted(glob.glob(os.path.join(R, "check", "*.json"))):
        J = json.load(open(jf)); ds = os.path.basename(jf)[:-5]
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            for G in (2, 4, 8):
                if G not in V or G + 100 not in V:
                    continue
                a, b = V[G], V[G + 100]
                L.append("| %s | %g | %d | %d | %d / %d | %d/%d | %d/%d | %.4f / %.4f |" % (
                    ds, run["alpha"], run["batch"], G, a.get("topck_nontie", -1), b.get("topck_nontie", -1),
                    b.get("vs_independent_topck_identical", -1), run["nused"],
                    b.get("vs_independent_final_identical", -1), run["nused"], a["recall"], b["recall"]))
                out["check"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"], G=G, nused=run["nused"],
                                         nontie_v62=a.get("topck_nontie"), nontie_v63=b.get("topck_nontie"),
                                         topck_identical=b.get("vs_independent_topck_identical"),
                                         final_identical=b.get("vs_independent_final_identical")))
    S = {}
    sp = os.path.join(R, "perf", "stages_summary.json")
    if os.path.exists(sp):
        for s in json.load(open(sp)):
            S[(s["tag"], float(s["alpha"]), s["batch"], s["G"])] = s
    L += ["", "## Performance: v63 (shared bound) against v62 (independent groups) at each G, and against G0", "",
          "| dataset | alpha | b | G | v63 over v62 (paired) | v62 over G0 | v63 over G0 | scan us v62 / v63 | merge us v62 / v63 | latency ms G0 / v62 / v63 |",
          "|---|---:|---:|---:|---|---|---|---|---|---|"]
    for jf in sorted(glob.glob(os.path.join(R, "perf", "*.json"))):
        if jf.endswith("stages_summary.json"):
            continue
        J = json.load(open(jf)); ds = os.path.basename(jf)[:-5]
        for run in J["runs"]:
            V = {v["G"]: v for v in run["variants"]}
            for G in (2, 4, 8):
                if G not in V or G + 100 not in V:
                    continue
                s63 = paired(V[G + 100]["qps"], V[G]["qps"])
                s62_0 = paired(V[G]["qps"], V[0]["qps"])
                s63_0 = paired(V[G + 100]["qps"], V[0]["qps"])
                k62 = S.get((ds, float(run["alpha"]), run["batch"], G))
                k63 = S.get((ds, float(run["alpha"]), run["batch"], G + 100))
                f = lambda x, st_: ("%.1f" % x["stages_us"][st_]) if x else "-"
                L.append("| %s | %g | %d | %d | x%.3f [%.3f, %.3f] | x%.3f | x%.3f | %s / %s | %s / %s | %.3f / %.3f / %.3f |" % (
                    ds, run["alpha"], run["batch"], G, *s63, s62_0[0], s63_0[0], f(k62, "scan"), f(k63, "scan"),
                    f(k62, "merge"), f(k63, "merge"), st.median(V[0]["lat_med_ms"]), st.median(V[G]["lat_med_ms"]),
                    st.median(V[G + 100]["lat_med_ms"])))
                out["perf"].append(dict(dataset=ds, alpha=run["alpha"], batch=run["batch"], G=G, v63_over_v62=s63,
                                        v62_over_g0=s62_0, v63_over_g0=s63_0,
                                        scan_us=(k62["stages_us"]["scan"] if k62 else None,
                                                 k63["stages_us"]["scan"] if k63 else None),
                                        merge_us=(k62["stages_us"]["merge"] if k62 else None,
                                                  k63["stages_us"]["merge"] if k63 else None)))
    open(os.path.join(R, "summary.md"), "w").write("\n".join(L) + "\n")
    json.dump(out, open(os.path.join(R, "summary.json"), "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
