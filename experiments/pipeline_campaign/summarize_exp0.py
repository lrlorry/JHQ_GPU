#!/usr/bin/env python3
"""Experiment 0 tables: native sm_120 against the compute_80 PTX build.

  python3 summarize_exp0.py <results/pipeline_campaign/exp0> <results/pipeline_v62/perf> <out.md>

A  ab/<ds>_sm{80,120}.json (demo_jhq_v61_ab, all queries in batches of 1024):
   L16 / L0 paired within each process (per-round time ratio, median [min,
   max]); sm_120 against compute_80 across the two processes (ratio of the
   median round times, same lanes) -- unpaired, so read it to a few percent.
B  batch/<ds>_sm120.json (demo_jhq_v62_batch built for sm_120) against
   pipeline_v62/perf/<ds>.json (the compute_80 Phase 3 run): each build's G
   speedups over its own G = 0, side by side, and the G = 0 latency ratio.
Measures nothing itself.
"""
import glob
import json
import os
import statistics as st
import sys


def paired(num, den):
    r = [a / b for a, b in zip(num, den)]
    return st.median(r), min(r), max(r)


def main():
    E, P62, out = sys.argv[1], sys.argv[2], sys.argv[3]
    L = ["# Experiment 0: native sm_120 against compute_80 PTX", "",
         "Generated by summarize_exp0.py. Same commit, same index (arms6 cache), same queries; "
         "the compute_80 build is what every earlier number came from (the driver JIT-compiles its PTX "
         "for the RTX 5090).", "",
         "## A. v61 refinement lanes 0 vs 16 (demo_jhq_v61_ab: all queries, batches of 1024, 5 rounds x 3 searches)", "",
         "| dataset | alpha | build | L0 ms | L16 ms | L16 speedup (paired) | recall L0 / L16 | L16 same order / set / bit-identical vs L0 |",
         "|---|---:|---|---:|---:|---|---|---|"]
    J = {"ab": [], "batch": []}
    ms = {}
    for jf in sorted(glob.glob(os.path.join(E, "ab", "*.json"))):
        tag = os.path.basename(jf)[:-5]
        ds, arch = tag.rsplit("_sm", 1)
        A = json.load(open(jf))
        for a in A["alphas"]:
            V = {v["lanes"]: v for v in a["variants"]}
            m0, m16 = st.median(V[0]["ms"]), st.median(V[16]["ms"])
            sp = paired(V[0]["ms"], V[16]["ms"])
            ms[(ds, a["alpha"], arch)] = (m0, m16)
            L.append("| %s | %g | %s | %.3f | %.3f | x%.3f [%.3f, %.3f] | %.4f / %.4f | %d / %d / %d of %d |" % (
                ds, a["alpha"], "sm_120" if arch == "120" else "compute_80", m0, m16, *sp,
                V[0]["recall"], V[16]["recall"], V[16]["same_order"], V[16]["same_set"], V[16]["bit_identical"], A["nq"]))
            J["ab"].append(dict(dataset=ds, alpha=a["alpha"], arch=arch, l0_ms=m0, l16_ms=m16, l16_speedup=sp,
                                recall_l0=V[0]["recall"], recall_l16=V[16]["recall"]))
    L += ["", "sm_120 against compute_80 (median round time ratio, compute_80 / sm_120; > 1 means native is faster):", "",
          "| dataset | alpha | L0 | L16 |", "|---|---:|---:|---:|"]
    for (ds, a, arch), (m0, m16) in sorted(ms.items()):
        if arch != "120" or (ds, a, "80") not in ms:
            continue
        o0, o16 = ms[(ds, a, "80")]
        L.append("| %s | %g | x%.3f | x%.3f |" % (ds, a, o0 / m0, o16 / m16))

    L += ["", "## B. v62 batch sweep: each build against its own G = 0 (paired, median [min, max] of 5 rounds)", "",
          "| dataset | alpha | b | G0 latency ms compute_80 / sm_120 | G2 c80 / s120 | G4 c80 / s120 | G8 c80 / s120 | recall c80 / s120 |",
          "|---|---:|---:|---|---|---|---|---|"]
    for jf in sorted(glob.glob(os.path.join(E, "batch", "*_sm120.json"))):
        ds = os.path.basename(jf)[:-len("_sm120.json")]
        N = json.load(open(jf))
        pf = os.path.join(P62, ds + ".json")
        O = json.load(open(pf)) if os.path.exists(pf) else {"runs": []}
        old = {(r["alpha"], r["batch"]): {v["G"]: v for v in r["variants"]} for r in O["runs"]}
        for r in N["runs"]:
            V = {v["G"]: v for v in r["variants"]}
            W = old.get((r["alpha"], r["batch"]), {})
            cells = []
            for G in (2, 4, 8):
                s_new = paired(V[G]["qps"], V[0]["qps"]) if G in V else None
                s_old = paired(W[G]["qps"], W[0]["qps"]) if G in W and 0 in W else None
                cells.append("%s / %s" % ("x%.2f" % s_old[0] if s_old else "-", "x%.2f" % s_new[0] if s_new else "-"))
            l_new = st.median(V[0]["lat_med_ms"])
            l_old = st.median(W[0]["lat_med_ms"]) if 0 in W else float("nan")
            L.append("| %s | %g | %d | %.3f / %.3f | %s | %s | %s | %.4f / %.4f |" % (
                ds, r["alpha"], r["batch"], l_old, l_new, *cells,
                W[0]["recall"] if 0 in W else float("nan"), V[0]["recall"]))
            J["batch"].append(dict(dataset=ds, alpha=r["alpha"], batch=r["batch"], g0_lat_c80=l_old, g0_lat_s120=l_new,
                                   speedup_s120={G: paired(V[G]["qps"], V[0]["qps"]) for G in (2, 4, 8) if G in V}))
    open(out, "w").write("\n".join(L) + "\n")
    json.dump(J, open(out[:-3] + ".json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
